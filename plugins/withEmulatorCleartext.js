/**
 * Expo config plugin (P2b, decision Q11): lets an Android APK built with the
 * EAS "emulator" profile reach the Firebase emulators on your PC over plain
 * http, and ONLY that one LAN address (plus the Android emulator's own
 * 10.0.2.2 and localhost). Every other build is untouched: Android's default
 * (no cleartext) stays in force.
 *
 * Active only when APP_VARIANT=emulator AND EXPO_PUBLIC_FIREBASE_EMULATOR_HOST
 * is a private IPv4 address (10.x, 172.16-31.x, 192.168.x). Anything else
 * fails the build instead of silently allowing cleartext.
 */
const { withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const PRIVATE_V4 = /^(10\.(\d{1,3})\.(\d{1,3})\.(\d{1,3})|192\.168\.(\d{1,3})\.(\d{1,3})|172\.(1[6-9]|2\d|3[01])\.(\d{1,3})\.(\d{1,3}))$/;

function emulatorHost(env = process.env) {
  if (env.APP_VARIANT !== 'emulator') return null;
  const host = (env.EXPO_PUBLIC_FIREBASE_EMULATOR_HOST || '').trim();
  if (!PRIVATE_V4.test(host) || host.split('.').some((n) => Number(n) > 255)) {
    throw new Error(`withEmulatorCleartext: EXPO_PUBLIC_FIREBASE_EMULATOR_HOST must be your PC's private Wi-Fi IPv4 address (got "${host}"). See TESTING_ON_DEVICE.md.`);
  }
  return host;
}

function networkSecurityXml(host) {
  const hosts = [host, '10.0.2.2', 'localhost', '127.0.0.1'];
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withEmulatorCleartext.js for the EAS "emulator" profile only. -->',
    '<network-security-config>',
    '  <base-config cleartextTrafficPermitted="false" />',
    '  <domain-config cleartextTrafficPermitted="true">',
    ...hosts.map((h) => `    <domain includeSubdomains="false">${h}</domain>`),
    '  </domain-config>',
    '</network-security-config>',
    '',
  ].join('\n');
}

module.exports = function withEmulatorCleartext(config) {
  const host = emulatorHost();
  if (!host) return config;
  config = withDangerousMod(config, [
    'android',
    async (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), networkSecurityXml(host));
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    const app = c.modResults.manifest.application?.[0];
    if (app) app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return c;
  });
};
module.exports.emulatorHost = emulatorHost;
module.exports.networkSecurityXml = networkSecurityXml;
