#!/usr/bin/env node
/**
 * Builds the editor WebView page.
 *   node scripts/build-editor.mjs          -> writes src/modules/editor/generated/editorHtml.ts
 *   node scripts/build-editor.mjs --check  -> exits 1 if the committed file is stale
 *
 * Steps:
 *  1. esbuild bundles editor-web/src/main.ts (TipTap + bridge) into one IIFE.
 *  2. Refuse output containing "</script" (it would break out of the tag).
 *  3. Pin the script with a CSP hash: script-src 'sha256-...'. No other
 *     script can run, and the page cannot load anything from the network.
 */
import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/modules/editor/generated/editorHtml.ts');
const check = process.argv.includes('--check');

export function buildCsp(scriptHash) {
  return [
    "default-src 'none'",
    `script-src 'sha256-${scriptHash}'`,
    "style-src 'unsafe-inline'",
    'img-src data:',
    'font-src data:',
    "connect-src 'none'",
    "media-src 'none'",
    "object-src 'none'",
    "frame-src 'none'",
    "worker-src 'none'",
    "manifest-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
}

const result = await build({
  entryPoints: [resolve(root, 'editor-web/src/main.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome108', 'safari16'],
  minify: true,
  legalComments: 'none',
  write: false,
  charset: 'utf8',
  tsconfig: resolve(root, 'tsconfig.json'),
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
});

const script = result.outputFiles[0].text.trim();
if (/<\/script/i.test(script)) {
  console.error('Bundle contains "</script" and cannot be inlined safely.');
  process.exit(1);
}
const hash = createHash('sha256').update(script, 'utf8').digest('base64');
const csp = buildCsp(hash);
// Git may check out text as CRLF on Windows and LF on Linux. Normalize only
// the template before inserting the bundled script so both platforms produce
// identical generated HTML without altering the script covered by the CSP hash.
const template = readFileSync(resolve(root, 'editor-web/src/template.html'), 'utf8').replace(/\r\n?/g, '\n');
const html = template.split('__CSP__').join(csp).split('__SCRIPT__').join(script);

const banner = `/* GENERATED by scripts/build-editor.mjs. Do not edit by hand. Run: npm run build:editor */\n/* eslint-disable */\n`;
const source =
  banner +
  `export const EDITOR_SCRIPT_SHA256 = ${JSON.stringify(hash)};\n` +
  `export const EDITOR_CSP = ${JSON.stringify(csp)};\n` +
  `export const EDITOR_SCRIPT_BYTES = ${Buffer.byteLength(script, 'utf8')};\n` +
  `export const EDITOR_HTML = ${JSON.stringify(html)};\n`;

if (check) {
  // The generated module itself can also be checked out as CRLF. Normalize
  // physical file line endings only; escaped characters inside its JS strings
  // remain untouched, so a genuinely stale editor is still rejected.
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8').replace(/\r\n?/g, '\n') : '';
  if (current !== source) {
    console.error('Editor HTML is stale. Run: npm run build:editor');
    process.exit(1);
  }
  console.log(`Editor HTML is up to date (${Buffer.byteLength(script)} bytes, sha256-${hash}).`);
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, source);
  console.log(`Wrote ${outFile} (${Buffer.byteLength(script)} bytes script, sha256-${hash}).`);
}
